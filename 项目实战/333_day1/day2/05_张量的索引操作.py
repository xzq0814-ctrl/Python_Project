"""
案例:
演示 张量的 索引操作.
分类:
简单行列索引*  列表索引  范围索引*  布尔索引   多维索引*
"""
import torch

torch.manual_seed(24)

t1 = torch.randint(1,10,(5,5))
print(f"t1 = {t1}")
# 行列索引
    # 获取第二行数据
print(t1[1])
print(t1[1, :])
print(t1[:, 2])
print('-'*30)
# 列表索引
    # 返回（0，1）（1，2）位置元素
print(t1[[0,1],[1,2]])

print(t1[[1,3],[2,4]])  # 返回什么元素

print(t1[[[0],[1]],[1,2]])
# 范围索引
    # 前三行，前两列
print(t1[:3,:2])
    # 2行到最后，前两列
print(t1[1:,:2])
    # 所有奇数行，偶数列
print(t1[1::2,::2])
# 布尔索引
    # 第三列，大于5的行数据
print(t1[t1[:,2]>5])
# 多维索引
    # 创建三维张量,2个3行4列的矩阵
t2 = torch.randint(1,10,(2,3,4))
print(f"t2 = {t2}")
    # 获取0轴上的第一个数据
print(t2[0,:,:])
    # 获取1轴上的第一个数据
print(t2[:,0,:])
