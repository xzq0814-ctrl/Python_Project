"""
循环网络层作用：
    基于上一次的隐藏状态+本次的输入→本次的隐藏状态，本次的输出。

    公式:
        本次的隐藏状态= tanh（上次的隐藏状态 加权求和+本次的输入 加权求和）
        本次的输出：本次的隐藏状态加权求和，有词汇表中所有词的概率，选概率最大的哪个词作为最终预测结果。
简单总结下RNN：
    词嵌入层：将词（词的索引）转换为词向量表示。
    RNN层（循环网络层）：逐步处理词向量，生成每个时间步的隐藏状态。
    全连接层（输出映射）：通过线性变换将隐藏状态映射到输出，通常是1个词汇表中词的概率分布。
"""
import torch.nn as nn
import torch
#1.创建 循环网络层rnn。
#参1：词向量的维度
#参2：隐藏状态向量维度
#参3：隐藏层数量，默认是1
rnn = nn.RNN(input_size=128,hidden_size=256,num_layers=1)
#2.定义变量，表示输入的X
#参1：每个句子的词的个数（长度），假设电影总共有5帧画面。
#参2：句子的数量， 同时有32个人在看这5帧画面。
#参3：词向量的维度。每一帧画面的细节是128个。
x = torch.randn(size=(5,32,128))
#3 记录：上一时刻的隐藏状态。
#参1：隐藏层的层数，RNN的层数，和num_layers一样，1层大脑。
#参2：句子的数量，批量大小，和上述的X一样，32个人
#参3：隐藏状态向量维度，和上述的hidden_size一样，256维。
h0 = torch.randn(size=(1,32,256))
# 4调用RNN处理，获取到当前时刻的预测值 和当前的隐藏状态。
output, h1 = rnn(x, h0)
# 每个预测之后的输出，包含上个隐藏状态的向量维度。
print(f'output:{output.shape}')
# 本次输入的隐藏状态，看完最后1帧信息后，最新的记忆，只关注最后1帧。
print(f'h1:{h1.shape}')



